import assert from 'node:assert/strict';
import {resolveVideoSource} from './resolve_source.mjs';
const id='7668119425446350122';
globalThis.location={href:`https://www.douyin.com/video/${id}`,origin:'https://www.douyin.com'};
const expected={id,width:2560,height:1440,duration:433.076};
let address={width:2560,height:1440,url_list:['https://example.com/video.mp4']};
let detailId=id;
globalThis.fetch=async()=>({ok:true,json:async()=>({status_code:0,aweme_detail:{aweme_id:detailId,video:{duration:433076,bit_rate:[{format:'mp4',play_addr:address}]}}})});
assert.equal((await resolveVideoSource(expected)).ok,true);
address={...address,width:1280,height:720};
assert.equal((await resolveVideoSource(expected)).code,'matching-quality-unavailable');
address={...address,width:2560,height:1440,url_list:['https://example.com/video.mpd']};
assert.equal((await resolveVideoSource(expected)).ok,false);
address={...address,url_list:['https://example.com/video.mp4?__vid=123']};
assert.equal((await resolveVideoSource(expected)).ok,false);
detailId='123';
assert.equal((await resolveVideoSource(expected)).ok,false);
detailId=id;
assert.equal((await resolveVideoSource({...expected,duration:30})).code,'video-mismatch');
location.href='https://www.douyin.com/video/123';
assert.equal((await resolveVideoSource(expected)).code,'video-changed');
location.href=`https://www.douyin.com/video/${id}`;
address={width:2560,height:1440,url_list:['https://example.com/video.mp4']};
const lowerPlayer={...expected,width:1280,height:720,minimumResolution:1440};
const fullQuality=await resolveVideoSource(lowerPlayer);
assert.equal(fullQuality.ok,true,'A 720p player must not hide an accessible 1440p full MP4');
assert.equal(fullQuality.resolution,1440);
address={...address,width:1920,height:1080};
assert.equal((await resolveVideoSource(lowerPlayer)).ok,false,'Never silently lower a requested 1440p minimum');
console.log('Resolver checks passed, including player/source quality separation.');
